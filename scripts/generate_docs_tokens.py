#!/usr/bin/env python3
"""Generate the RefData Hub documentation theme tokens.

The MkDocs site and the Reviewer UI must look like one product. Rather than
hand-copying hex values from ``reviewer-ui/src/styles.css`` into
``docs/stylesheets/tokens.css`` (which silently drifts), this script extracts
the palette blocks and the structural tokens straight out of the app stylesheet
and emits the documentation theme layer.

Run after any palette change in the app::

    python scripts/generate_docs_tokens.py

The output is committed; CI does not regenerate it.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "reviewer-ui" / "src" / "styles.css"
TARGET = REPO_ROOT / "docs" / "stylesheets" / "tokens.css"

# Palettes must appear in this order in the generated file so that later
# ``[data-theme="..."]`` blocks win over the ``:root`` / Material scheme bases.
PALETTE_ORDER = [
    "light",
    "dark",
    "midnight-marina",
    "burj-gold",
    "desert-dusk",
    "oasis",
    "harbour-blue",
    "aurora",
    "coral-reef",
    "classic-dark",
    "classic-light",
    "midnight",
]

# Structural tokens lifted from the app's ``@theme`` block. These are not
# colour values but the geometry/motion primitives shared by both surfaces.
STRUCTURAL_TOKENS = [
    ("--radius-sm", "6px"),
    ("--radius-md", "10px"),
    ("--radius-lg", "14px"),
    ("--radius-xl", "20px"),
    ("--transition-fast", "150ms cubic-bezier(0.4, 0, 0.2, 1)"),
    ("--transition-normal", "250ms cubic-bezier(0.4, 0, 0.2, 1)"),
]

# Tailwind defaults the app relies on but does not redefine in ``@theme``.
TAILWIND_DEFAULTS = [
    ("--shadow-2xs", "0 1px rgb(0 0 0 / 0.05)"),
    ("--shadow-xs", "0 1px 2px 0 rgb(0 0 0 / 0.05)"),
]

BLOCK_RE = re.compile(r"^(\[data-theme=\"[^\"]+\"\](?:,\s*)?.*?)\s*\{\s*$")
BASE_LIGHT_SELECTOR = re.compile(r"^:root\s*$")


def extract_palettes(source: str) -> dict[str, str]:
    """Return ``{palette_id: declaration_block}`` from the app stylesheet."""
    palettes: dict[str, str] = {}
    lines = source.splitlines()
    index = 0

    while index < len(lines):
        line = lines[index].strip()

        if line == ":root," and index + 1 < len(lines):
            if lines[index + 1].strip() == '[data-theme="light"] {':
                palettes["light"] = _read_block(lines, index + 1)
                index += 1
        elif BLOCK_RE.match(line) and line.endswith("{"):
            palette_id = re.match(r'^\[data-theme="([^"]+)"\]', line).group(1)
            palettes[palette_id] = _read_block(lines, index)

        index += 1

    return palettes


def _read_block(lines: list[str], open_index: int) -> str:
    """Collect declarations from a ``{ ... }`` block starting at ``open_index``."""
    body: list[str] = []
    for raw in lines[open_index + 1 :]:
        if raw.strip() == "}":
            break
        if raw.strip():
            body.append(raw.rstrip())
    return "\n".join(body)


def render(palettes: dict[str, str]) -> str:
    missing = [name for name in PALETTE_ORDER if name not in palettes]
    if missing:
        raise SystemExit(
            "Expected palettes missing from "
            f"{SOURCE}: {', '.join(missing)}"
        )

    out: list[str] = []
    out.append("/*")
    out.append("  RefData Hub documentation theme tokens.")
    out.append("")
    out.append("  AUTO-GENERATED by scripts/generate_docs_tokens.py -- do not edit by")
    out.append(f"  hand. Source of truth: {SOURCE.relative_to(REPO_ROOT)}")
    out.append("")
    out.append("  Regenerate with: python scripts/generate_docs_tokens.py")
    out.append("*/")
    out.append("")

    out.append("/* -------------------------------------------------------------------------")
    out.append("   Structural tokens (geometry + motion, shared with the Reviewer UI)")
    out.append("   ------------------------------------------------------------------------- */")
    out.append("")
    out.append(":root {")
    for name, value in STRUCTURAL_TOKENS + TAILWIND_DEFAULTS:
        out.append(f"  {name}: {value};")
    out.append("}")
    out.append("")

    out.append("/* -------------------------------------------------------------------------")
    out.append("   Base palette")
    out.append("")
    out.append("   Keyed ONLY on `:root` / `[data-theme]`, never on Material's")
    out.append("   `[data-md-color-scheme]`. Material's bundle.js writes")
    out.append("   `data-md-color-scheme` onto <body> on every page, so a selector keyed")
    out.append("   on that attribute would re-impose its palette across the whole")
    out.append("   document and defeat the switcher. <html> always carries a")
    out.append("   `data-theme` from the anti-flash script in overrides/main.html, and")
    out.append("   `:root` covers the pre-JS first paint.")
    out.append("   ------------------------------------------------------------------------- */")
    out.append("")

    out.append(":root,")
    out.append('[data-theme="light"] {')
    out.append(palettes["light"])
    out.append("}")
    out.append("")

    out.append("/* -------------------------------------------------------------------------")
    out.append("   Full palette set")
    out.append("")
    out.append("   These come after the base block, so an explicit `[data-theme]")
    out.append("   selection always wins over the `:root` default.")
    out.append("   ------------------------------------------------------------------------- */")
    out.append("")

    for palette_id in PALETTE_ORDER:
        label = palette_id.replace("-", " ").title()
        out.append(f"/* {label} */")
        out.append(f'[data-theme="{palette_id}"] {{')
        out.append(palettes[palette_id])
        out.append("}")
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    palettes = extract_palettes(SOURCE.read_text(encoding="utf-8"))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(palettes), encoding="utf-8")
    print(
        f"Wrote {TARGET.relative_to(REPO_ROOT)} "
        f"({len(palettes)} palettes, {len(TARGET.read_text().splitlines())} lines)"
    )


if __name__ == "__main__":
    main()